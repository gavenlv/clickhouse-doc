-- │              ClickHouse 连接问题排查                         │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  常见连接问题:                                              │
-- │                                                              │
-- │  1. 网络连接问题                                            │
-- │     - 防火墙阻止端口                                        │
