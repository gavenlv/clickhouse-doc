-- │     - IP白名单限制                                          │
-- │                                                              │
-- │  3. 服务问题                                                │
-- │     - ClickHouse服务未启动                                  │
-- │     - 端口被占用                                            │
-- │     - 资源耗尽 (连接数满)                                   │
-- │                                                              │
-- │  端口说明:                                                  │
-- │  ┌──────────────┬──────────────────────────────────────┐   │
-- │  │    端口      │              用途                     │   │
-- │  ├──────────────┼──────────────────────────────────────┤   │
-- │  │ 8123         │ HTTP接口 (默认)                      │   │
-- │  │ 9000         │ Native接口 (TCP)                     │   │
-- │  │ 9004         │ MySQL兼容接口                        │   │
-- │  │ 9005         │ PostgreSQL兼容接口                   │   │
-- │  │ 9009         │ 集群间通信                           │   │
-- │  │ 9181         │ ClickHouse Keeper                   │   │
-- │  └──────────────┴──────────────────────────────────────┘   │
-- │                                                              │
-- │  排查步骤:                                                  │
-- │  1. 检查服务状态: systemctl status clickhouse-server       │
-- │  2. 检查端口监听: netstat -tlnp | grep 9000                │
-- │  3. 测试连接: clickhouse-client                            │
-- │  4. 检查日志: /var/log/clickhouse-server/                  │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

