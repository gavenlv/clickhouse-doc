-- 本文件涵盖:
--   1. 性能基准测试 - 测试插入、查询、聚合性能
--   2. CPU 监控 - CPU 使用率分析
--   3. 内存监控 - 内存使用分析
--   4. 磁盘监控 - 磁盘IO分析
-- 
-- 硬件资源配置建议:
-- 
--   ┌─────────────────────────────────────────────────────────────────────────┐
--   │                    ClickHouse 硬件配置建议                              │
--   └─────────────────────────────────────────────────────────────────────────┘
--   
--   CPU:
--   ┌────────────────────────────────────────────────────────────────────────┐
--   │ - 建议: 现代 x86_64 CPU, 8+ 核心                                       │
--   │ - 关键参数: max_threads (默认 = CPU 核心数)                            │
--   │ - 影响: 并行查询性能、压缩/解压缩速度                                  │
--   └────────────────────────────────────────────────────────────────────────┘
--   
--   内存:
--   ┌────────────────────────────────────────────────────────────────────────┐
--   │ - 建议: 16GB+ (生产环境建议 64GB+)                                     │
--   │ - 关键参数: max_memory_usage (默认 10GB)                               │
--   │ - 用途: 查询执行、排序、聚合、缓存                                     │
--   │ - 建议: 内存 >= 数据量/10 (热数据)                                     │
--   └────────────────────────────────────────────────────────────────────────┘
--   
--   磁盘:
--   ┌────────────────────────────────────────────────────────────────────────┐
--   │ - 建议: NVMe SSD (顺序读写 > 1GB/s)                                    │
--   │ - 避免使用: HDD, 网络存储 (除非分布式)                                 │
--   │ - 用途: 数据存储、合并操作、临时文件                                   │
--   │ - 建议: 磁盘空间 >= 数据量 * 3 (考虑合并和临时文件)                    │
--   └────────────────────────────────────────────────────────────────────────┘
-- 
-- 性能测试流程:
-- 
--   ┌─────────────────────────────────────────────────────────────────────────┐
--   │                    性能基准测试步骤                                     │
--   └─────────────────────────────────────────────────────────────────────────┘
--   
--   1. 插入测试:
--      ┌──────────┐    ┌──────────┐    ┌──────────┐
--      │ 准备数据 │───>│ 批量插入 │───>│ 记录耗时 │
--      │ 100万行  │    │          │    │          │
--      └──────────┘    └──────────┘    └──────────┘
--      
--      指标: 行/秒, MB/秒
--      正常: > 10万行/秒 (HDD), > 100万行/秒 (SSD)
--   
--   2. 查询测试:
--      ┌──────────┐    ┌──────────┐    ┌──────────┐
--      │ 执行查询 │───>│ 记录耗时 │───>│ 分析结果 │
--      │ 简单聚合 │    │          │    │          │
--      └──────────┘    └──────────┘    └──────────┘
--      
--      指标: 查询时间, 扫描行数/秒
--      正常: > 1亿行/秒 (简单查询)
--   
--   3. JOIN 测试:
--      ┌──────────┐    ┌──────────┐
--      │ 执行JOIN │───>│ 记录耗时 │
--      │  多表    │    │          │
--      └──────────┘    └──────────┘
--      
--      指标: JOIN 时间
--      正常: 取决于表大小和 JOIN 策略
-- 
-- ================================================================================

INSERT INTO events
SELECT 
    number as event_id,
    number % 10000 as user_id,
    'click' as event_type,
    now() as event_time,
    '{}' as event_data
FROM numbers(1000000);

-- 测试查询性能
SELECT count() FROM events;

-- 测试聚合性能
SELECT 
    user_id,
    count() as event_count
FROM events
GROUP BY user_id;

-- 测试 JOIN 性能
SELECT 
    o.order_id,
    u.username
FROM orders o
INNER JOIN users u ON o.user_id = u.user_id;

