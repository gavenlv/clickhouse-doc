-- 查看分片数据分布
SELECT 
    remote_hostname,
    sum(rows) AS rows,
    formatReadableSize(sum(bytes)) AS size
FROM system.parts
WHERE database = 'tutorial' AND table = 'local_events' AND active = 1
GROUP BY remote_hostname;

-- 查看查询执行时间分布
SELECT 
    endpoint,
    sum(rows) AS total_rows,
    avg(elapsed) AS avg_time,
    count() AS query_count
FROM system.metric_log
WHERE event_time > now() - INTERVAL 1 HOUR
GROUP BY endpoint;

