-- 3. 分布式查询原理
-- -----------------------------------------------------

-- 分布式查询执行流程:
--
-- ┌─────────────────────────────────────────────────────────────┐
-- │              分布式查询执行流程                                  │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  查询: SELECT count(), sum(value) FROM events               │
-- │        WHERE date = '2024-01-01'                           │
-- │                                                              │
-- │  Step 1: 查询规划                                             │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  ┌─────────────────────────────────────────────┐   │   │
-- │  │  │  Distributed                                │   │   │
-- │  │  │  ├── 分解为子查询发送到各分片               │   │   │
-- │  │  │  ├── SELECT count(), sum(value)          │   │   │
-- │  │  │  │     FROM local_events                  │   │   │
-- │  │  │  │     WHERE date = '2024-01-01'           │   │   │
-- │  │  │  │     GROUP BY date                      │   │   │
-- │  │  │  └──                                        │   │   │
-- │  │  └─────────────────────────────────────────────┘   │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                            │                                 │
-- │                            ▼                                 │
-- │  Step 2: 并行执行                                            │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  ┌─────────┐  ┌─────────┐  ┌─────────┐            │   │
-- │  │  │ Shard 1 │  │ Shard 2 │  │ Shard 3 │            │   │
-- │  │  │   │     │  │   │     │  │   │     │            │   │
-- │  │  │ count:5 │  │count:8 │  │count:3 │            │   │
-- │  │  │ sum:50  │  │sum:120 │  │sum:25  │            │   │
-- │  │  └────┬────┘  └────┬────┘  └────┬────┘            │   │
-- │  └───────┼───────────┼───────────┼────────────────────┘   │
-- │          │           │           │                        │
-- │          └───────────┴───────────┘                        │
-- │                            │                                 │
-- │                            ▼                                 │
-- │  Step 3: 合并结果                                           │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  count = 5 + 8 + 3 = 16                            │   │
-- │  │  sum   = 50 + 120 + 25 = 195                      │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

-- 3.1 本地 vs 分布式查询
--
-- ┌─────────────────────────────────────────────────────────────┐
-- │              本地查询 vs 分布式查询                              │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  本地查询 (Local Table):                                      │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │                                                      │   │
-- │  │  SELECT * FROM local_events                         │   │
-- │  │         │                                           │   │
-- │  │         ▼                                           │   │
-- │  │  直接读取本地 MergeTree                            │   │
-- │  │  特点: ✓ 最快                                       │   │
-- │  │        ✓ 可利用索引                                 │   │
-- │  │        ✗ 单节点资源有限                             │   │
-- │  │                                                      │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  分布式查询 (Distributed Table):                              │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │                                                      │   │
-- │  │  SELECT * FROM distributed_events                  │   │
-- │  │         │                                           │   │
-- │  │         ▼                                           │   │
-- │  │  ┌─────────────────────────────────────────────┐   │   │
-- │  │  │  Coordinator (分布式引擎)                     │   │   │
-- │  │  │  ├── 发送子查询到各分片                       │   │   │
-- │  │  │  ├── 收集结果                                 │   │   │
-- │  │  │  └── 合并返回                                 │   │   │
-- │  │  └─────────────────────────────────────────────┘   │   │
-- │  │         │                                           │   │
-- │  │         ▼                                           │   │
-- │  │  特点: ✓ 扩展性好                                  │   │
-- │  │        ✓ 并行处理                                  │   │
-- │  │        ✗ 网络开销                                  │   │
-- │  │                                                      │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

-- -----------------------------------------------------
-- 4. 分布式表创建
-- -----------------------------------------------------

CREATE DATABASE IF NOT EXISTS tutorial;

-- 4.1 创建本地表 (每个分片上的实际存储表)
DROP TABLE IF EXISTS tutorial.local_events;

CREATE TABLE IF NOT EXISTS tutorial.local_events (
    id UInt64,
    event_date Date,
    user_id UInt32,
    event_type String,
    value Float64
) ENGINE = MergeTree()
PARTITION BY toYYYYMM(event_date)
ORDER BY (event_date, user_id);

-- 4.2 创建分布式表 (逻辑表,自动路由)
DROP TABLE IF EXISTS tutorial.distributed_events;

CREATE TABLE IF NOT EXISTS tutorial.distributed_events
ENGINE = Distributed(
    'treasurycluster',    -- 集群名称 (在 config.xml 中配置)
    'tutorial',          -- 数据库名
    'local_events',     -- 本地表名
    sipHash64(user_id)   -- 分片键 (可选)
);

-- 查看分布式表信息
SELECT 
    database,
    table,
    engine,
    cluster,
    sharding_key,
    formatReadableSize(bytes_on_disk) AS size
FROM system.tables
WHERE database = 'tutorial' AND table = 'distributed_events';

-- -----------------------------------------------------
-- 5. 分片键类型演示
-- -----------------------------------------------------

-- 5.1 随机分片 - 数据均匀但无法局部查询
DROP TABLE IF EXISTS tutorial.random_sharded;

CREATE TABLE IF NOT EXISTS tutorial.random_sharded (
    id UInt64,
    user_id UInt32,
    value Float64
) ENGINE = Distributed(
    'treasurycluster',
    'tutorial', 
    'local_events',
    rand()  -- 随机分片
);

-- 5.2 哈希分片 - 相同用户数据在一起
DROP TABLE IF EXISTS tutorial.hash_sharded;

CREATE TABLE IF NOT EXISTS tutorial.hash_sharded (
    id UInt64,
    user_id UInt32,
    value Float64
) ENGINE = Distributed(
    'treasurycluster',
    'tutorial',
    'local_events',
    sipHash64(user_id)  -- 按用户哈希
);

-- 5.3 日期分片 - 按时间范围分片
DROP TABLE IF EXISTS tutorial.date_sharded;

CREATE TABLE IF NOT EXISTS tutorial.date_sharded (
    id UInt64,
    event_date Date,
    user_id UInt32,
    value Float64
) ENGINE = Distributed(
    'treasurycluster',
    'tutorial',
    'local_events',
    toYYYYMM(event_date)  -- 按月分片
);

-- 5.4 复合分片 - 平衡热点
DROP TABLE IF EXISTS tutorial.composite_sharded;

CREATE TABLE IF NOT EXISTS tutorial.composite_sharded (
    id UInt64,
    user_id UInt32,
    tenant_id UInt32,  -- 多租户 ID
    value Float64
) ENGINE = Distributed(
    'treasurycluster',
    'tutorial',
    'local_events',
    sipHash64(tenant_id, user_id)  -- 复合键分片
);

