-- 6. 分布式查询优化
-- -----------------------------------------------------

-- 6.1 使用 LOCAL TABLE 避免跨分片
--
-- ┌─────────────────────────────────────────────────────────────┐
-- │              分布式查询优化技巧                                 │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  技巧 1: 使用 LOCAL TABLE 查询                               │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │                                                      │   │
-- │  │  ✗ SELECT * FROM distributed_events               │   │
-- │  │    → 查询所有分片                                   │   │
-- │  │                                                      │   │
-- │  │  ✓ SELECT * FROM tutorial.local_events             │   │
-- │  │    → 查询本地节点                                   │   │
-- │  │                                                      │   │
-- │  │  ✓ SELECT * FROM distributed_events LOCAL          │   │
-- │  │    → 只查询本地分片                                 │   │
-- │  │                                                      │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  技巧 2: 利用分片键过滤                                       │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │                                                      │   │
-- │  │  SELECT * FROM distributed_events                  │   │
-- │  │  WHERE user_id = 123                               │   │
-- │  │  → 利用分片键,只扫描包含 user_id=123 的分片       │   │
-- │  │                                                      │   │
-- │  │  SELECT * FROM distributed_events                  │   │
-- │  │  WHERE event_date BETWEEN '2024-01-01' AND '2024-01-31'│   │
-- │  │  → 只扫描包含该日期范围的分片                      │   │
-- │  │                                                      │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  技巧 3: 预聚合减少数据传输                                    │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │                                                      │   │
-- │  │  ✗ SELECT user_id, count() FROM distributed_events │   │
-- │  │    GROUP BY user_id                                │   │
-- │  │    → 传输大量原始数据                               │   │
-- │  │                                                      │   │
-- │  │  ✓ SELECT user_id, uniqExact(user_id) ...         │   │
-- │  │    FROM distributed_events                         │   │
-- │  │    GROUP BY user_id                                │   │
-- │  │    → 使用分布式聚合函数,减少传输                   │   │
-- │  │                                                      │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

-- 6.2 分布式聚合
--
-- ┌─────────────────────────────────────────────────────────────┐
-- │              分布式聚合执行流程                                  │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  两阶段聚合:                                                  │
-- │                                                              │
-- │  Stage 1: 每个分片本地聚合                                     │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  Shard 1: SELECT user_id, count() AS cnt           │   │
-- │  │           FROM local_events                         │   │
-- │  │           WHERE user_id IN (1,2,3)                 │   │
-- │  │           GROUP BY user_id                        │   │
-- │  │           → {user_id:1, cnt:100}                  │   │
-- │  │           → {user_id:2, cnt:80}                   │   │
-- │  │                                                      │   │
-- │  │  Shard 2: → {user_id:1, cnt:120}                  │   │
-- │  │           → {user_id:3, cnt:90}                   │   │
-- │  │                                                      │   │
-- │  │  Shard 3: → {user_id:2, cnt:70}                   │   │
-- │  │           → {user_id:3, cnt:110}                  │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                            │                                 │
-- │                            ▼                                 │
-- │  Stage 2: 协调节点合并                                        │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  user_id: 1 → 100 + 120 = 220                     │   │
-- │  │  user_id: 2 → 80 + 70 = 150                      │   │
-- │  │  user_id: 3 → 90 + 110 = 200                     │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  分布式聚合函数:                                              │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  count()       → count()       (自动分布式)        │   │
-- │  │  sum()         → sum()         (自动分布式)        │   │
-- │  │  uniq()        → uniqMerge()   (需要手动合并)      │   │
-- │  │  quantile()    → quantileMerge()(需要手动合并)    │   │
-- │  │  groupArray()  → groupArrayMerge()                │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

-- -----------------------------------------------------
-- 7. 跨分片操作
-- -----------------------------------------------------

-- 7.1 跨分片 JOIN
--
-- ┌─────────────────────────────────────────────────────────────┐
-- │              跨分片 JOIN 原理                                   │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  场景:                                                        │
-- │  SELECT e.*, u.name                                        │
-- │  FROM distributed_events e                                 │
-- │  JOIN users u ON e.user_id = u.id                          │
-- │                                                              │
-- │  执行策略:                                                    │
-- │                                                              │
-- │  1. 广播 JOIN (小表)                                          │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  users 表较小 → 复制到所有分片                      │   │
-- │  │                                                      │   │
-- │  │  Shard 1: [events] + [users 副本]                  │   │
-- │  │  Shard 2: [events] + [users 副本]                  │   │
-- │  │  Shard 3: [events] + [users 副本]                  │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                            │                                 │
-- │                            ▼                                 │
-- │  2. 哈希 JOIN (大表)                                         │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  按 JOIN key 重新分配数据                           │   │
-- │  │                                                      │   │
-- │  │  Shard 1: events.user_id%3=0 + users.id%3=0       │   │
-- │  │  Shard 2: events.user_id%3=1 + users.id%3=1       │   │
-- │  │  Shard 3: events.user_id%3=2 + users.id%3=2       │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                            │                                 │
-- │                            ▼                                 │
-- │  3. 全局 JOIN                                                │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  收集到协调节点处理                                  │   │
-- │  │                                                      │   │
-- │  │  [Sh1_events] ─┐                                    │   │
-- │  │  [Sh2_events] ─┼──► 合并 ──► JOIN ──► 返回         │   │
-- │  │  [Sh3_events] ─┘    协调节点                        │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

-- 7.2 全局 Distributed 表
--
-- 创建全局分布式表 (跨集群)
DROP TABLE IF EXISTS tutorial.global_events;

CREATE TABLE IF NOT EXISTS tutorial.global_events
ENGINE = Distributed(
    'cluster1,cluster2',  -- 多个集群
    'tutorial',
    'local_events',
    sipHash64(user_id)
);

