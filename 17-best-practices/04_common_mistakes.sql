-- 1. 写入相关错误
-- -----------------------------------------------------

-- 
-- ┌─────────────────────────────────────────────────────────────┐
-- │              常见写入错误                                        │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  错误 1: 频繁小批量写入                                        │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │ 症状:                                               │   │
-- │  │ • 大量小 Parts,合并压力巨大                         │   │
-- │  │ • 查询性能逐渐下降                                  │   │
-- │  │ • 磁盘 I/O 持续高位                                │   │
-- │  │                                                      │   │
-- │  │ 解决方案:                                           │   │
-- │  │ • 批量写入,每批 > 10万行                          │   │
-- │  │ • 使用异步写入 async_insert = 1                   │   │
-- │  │ • 积攒数据后批量写入                               │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  错误 2: 写入时无分区键值                                      │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │ 症状:                                               │   │
-- │  │ • 写入失败: "There is no partition column"        │   │
-- │  │                                                      │   │
-- │  │ 解决方案:                                           │   │
-- │  │ • 提供分区键值                                      │   │
-- │  │ • 或使用 DEFAULT 表达式                            │   │
-- │  │ • 或修改表结构为无分区                             │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  错误 3: 数据类型不匹配                                        │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │ 症状:                                               │   │
-- │  │ • "Type mismatch" 错误                             │   │
-- │  │ • 数据被截断                                        │   │
-- │  │                                                      │   │
-- │  │ 解决方案:                                           │   │
-- │  │ • 使用 CAST 函数转换                                │   │
-- │  │ • 确保写入数据类型与表定义匹配                     │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

-- 演示: 批量写入 vs 小写入
CREATE DATABASE IF NOT EXISTS tutorial;

DROP TABLE IF EXISTS tutorial.batch_test;

CREATE TABLE IF NOT EXISTS tutorial.batch_test (
    id UInt64,
    value Float64
) ENGINE = MergeTree()
ORDER BY id;

-- Good: 批量写入
INSERT INTO tutorial.batch_test
SELECT number, rand() / 100.0
FROM numbers(100000);

SELECT 
    '批量写入' AS type,
    count() AS rows,
    (SELECT count() FROM system.parts 
     WHERE database = 'tutorial' AND table = 'batch_test' AND active = 1) AS parts
FROM tutorial.batch_test;

