-- -----------------------------------------------------
-- 4.1 频繁更改数据的后果
-- -----------------------------------------------------

-- 
-- ┌─────────────────────────────────────────────────────────────┐
-- │              频繁更改数据的后果                                   │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  为什么 ClickHouse 不适合频繁更新?                              │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │                                                      │   │
-- │  │  ClickHouse 是列式存储数据库                        │   │
-- │  │  写入时按列存储,更新需要:                          │   │
-- │  │  1. 读取完整的列数据                               │   │
-- │  │  2. 修改对应行                                    │   │
-- │  │  3. 重新压缩写入                                  │   │
-- │  │                                                      │   │
-- │  │  这比写入新数据代价高得多!                        │   │
-- │  │                                                      │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  频繁更新的后果:                                              │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  1. 性能严重下降                                   │   │
-- │  │     - UPDATE 操作需要重写整个 Part                │   │
-- │  │     - 比 INSERT 慢 10-100 倍                     │   │
-- │  │                                                      │   │
-- │  │  2. 存储碎片化                                     │   │
-- │  │     - 产生大量小 Parts                            │   │
-- │  │     - 合并压力巨大                                │   │
-- │  │                                                      │   │
-- │  │  3. 磁盘 I/O 激增                                 │   │
-- │  │     - 频繁读写放大 I/O                            │   │
-- │  │     - 影响查询性能                                │   │
-- │  │                                                      │   │
-- │  │  4. 内存压力                                       │   │
-- │  │     - 读取整个列到内存                            │   │
-- │  │     - 大列更新导致内存峰值                        │   │
-- │  │                                                      │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  示例: 频繁更新 vs 批量写入对比                                │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  场景: 更新 10000 行数据                          │   │
-- │  │                                                      │   │
-- │  │  频繁更新:                                         │   │
-- │  │  for i in 1..10000:                              │   │
-- │  │      ALTER TABLE t UPDATE col = value            │   │
-- │  │      WHERE id = i;                               │   │
-- │  │  时间: 10000 * 100ms = 1000秒                   │   │
-- │  │                                                      │   │
-- │  │  批量更新:                                         │   │
-- │  │  ALTER TABLE t UPDATE col = value               │   │
-- │  │  WHERE id IN (1, 2, ..., 10000);               │   │
-- │  │  时间: ~1秒                                        │   │
-- │  │                                                      │   │
-- │  │  差距: 1000x!                                     │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  解决方案:                                                    │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  1. 在 ETL 阶段完成数据清洗                        │   │
-- │  │     - 源头保证数据正确                             │   │
-- │  │                                                      │   │
-- │  │  2. 使用物化视图预聚合                             │   │
-- │  │     - 减少实时计算                                │   │
-- │  │                                                      │   │
-- │  │  3. 使用 CollapsingMergeTree                      │   │
-- │  │     - 增量更新而非覆盖更新                        │   │
-- │  │                                                      │   │
-- │  │  4. 设计时考虑不可变性                            │   │
-- │  │     - 事件日志不应修改                            │   │
-- │  │     - 使用新批次而非更新                          │   │
-- │  │                                                      │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

