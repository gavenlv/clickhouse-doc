-- 查看最近错误
SELECT event_time, message
FROM system.logs
WHERE level = 'Error'
  AND event_time > now() - INTERVAL 1 HOUR
ORDER BY event_time DESC
LIMIT 10;

-- 查看 Parts 状态
SELECT 
    database,
    table,
    count() AS total_parts,
    countIf(active = 0) AS inactive_parts,
    sum(rows) AS total_rows
FROM system.parts
GROUP BY database, table
LIMIT 10;

