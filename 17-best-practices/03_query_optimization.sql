CREATE DATABASE IF NOT EXISTS tutorial;

DROP TABLE IF EXISTS tutorial.orders;

CREATE TABLE IF NOT EXISTS tutorial.orders (
    order_id UInt64,
    user_id UInt32,
    order_date DateTime,
    status Enum8('pending' = 1, 'paid' = 2, 'shipped' = 3, 'completed' = 4, 'cancelled' = 5),
    total_amount Decimal(10, 2),
    product_count UInt16,
    notes String
) ENGINE = MergeTree()
PARTITION BY toYYYYMM(order_date)
ORDER BY (order_date, user_id)
SETTINGS index_granularity = 8192;

-- 插入 100万条测试数据
INSERT INTO tutorial.orders
SELECT 
    number AS order_id,
    number % 50000 AS user_id,
    toDateTime('2024-01-01') + (number % 365) * 86400 + (number % 86400) AS order_date,
    CAST(number % 5 + 1 AS Enum8('pending' = 1, 'paid' = 2, 'shipped' = 3, 'completed' = 4, 'cancelled' = 5)),
    (rand() % 10000) / 100.0 AS total_amount,
    (rand() % 10) + 1 AS product_count,
    repeat('note-', 50)
FROM numbers(1000000);

-- -----------------------------------------------------
-- 3. 列裁剪优化
-- -----------------------------------------------------

-- 3.1 SELECT * vs SELECT 具体列
--
-- ┌─────────────────────────────────────────────────────────────┐
-- │              列裁剪性能对比                                      │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  Bad: SELECT *                                              │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  SELECT * FROM orders                               │   │
-- │  │  WHERE order_date = '2024-01-01';                  │   │
-- │  │                                                      │   │
-- │  │  读取所有列: order_id, user_id, order_date,       │   │
-- │  │            status, total_amount, product_count,   │   │
-- │  │            notes                                   │   │
-- │  │                                                      │   │
-- │  │  时间: ~200ms                                      │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                            │                                 │
-- │                            ▼                                 │
-- │  Good: SELECT 具体列                                         │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  SELECT user_id, count(), sum(total_amount)        │   │
-- │  │  FROM orders                                       │   │
-- │  │  WHERE order_date = '2024-01-01'                  │   │
-- │  │  GROUP BY user_id;                                │   │
-- │  │                                                      │   │
-- │  │  只读取需要的列: user_id, order_date, total_amount │   │
-- │  │                                                      │   │
-- │  │  时间: ~50ms (4x 提升)                            │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

-- 对比执行
SET max_threads = 1;

-- Bad
EXPLAIN PLAN
SELECT * FROM tutorial.orders
WHERE order_date >= '2024-01-01' AND order_date < '2024-01-02'
LIMIT 100;

-- Good
EXPLAIN PLAN
SELECT user_id, count() AS cnt, sum(total_amount) AS total
FROM tutorial.orders
WHERE order_date >= '2024-01-01' AND order_date < '2024-01-02'
GROUP BY user_id
LIMIT 100;

-- -----------------------------------------------------
-- 4. PREWHERE 优化
-- -----------------------------------------------------

-- 
-- ┌─────────────────────────────────────────────────────────────┐
-- │              PREWHERE 优化原理                                  │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  PREWHERE: 自动优化读取顺序                                   │
-- │                                                              │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  SELECT user_id, notes                             │   │
-- │  │  FROM orders                                       │   │
-- │  │  WHERE user_id = 123;                             │   │
-- │  │                                                      │   │
-- │  │  执行流程:                                          │   │
-- │  │  1. 先读取 user_id 列,过滤                        │   │
-- │  │  2. 只读取满足条件的 notes 列                     │   │
-- │  │                                                      │   │
-- │  │  ✓ 减少 I/O 量                                    │   │
-- │  │  ✓ 自动应用,无需手动指定                          │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  控制 PREWHERE:                                              │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  SET optimize_move_to_prewhere = 1;  (默认开启)   │   │
-- │  │  SET enable_optimize_predicate_expression = 1;    │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

-- 查看 PREWHERE 优化
EXPLAIN PIPELINE
SELECT user_id, notes
FROM tutorial.orders
WHERE user_id = 123;

-- -----------------------------------------------------
-- 5. 分区裁剪优化
-- -----------------------------------------------------

-- 
-- ┌─────────────────────────────────────────────────────────────┐
-- │              分区裁剪优化                                        │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  Bad: 在分区键上使用函数                                       │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  SELECT * FROM orders                               │   │
-- │  │  WHERE toYYYYMM(order_date) = 202401;              │   │
-- │  │                                                      │   │
-- │  │  ✗ 无法使用分区裁剪,全表扫描                       │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                            │                                 │
-- │                            ▼                                 │
-- │  Good: 直接使用分区键比较                                       │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  SELECT * FROM orders                               │   │
-- │  │  WHERE order_date >= '2024-01-01'                 │   │
-- │  │    AND order_date < '2024-02-01';                │   │
-- │  │                                                      │   │
-- │  │  ✓ 利用分区裁剪,只扫描 202401 分区                 │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

-- Bad: 使用函数
EXPLAIN ESTIMATE
SELECT * FROM tutorial.orders
WHERE toYYYYMM(order_date) = 202401;

-- Good: 直接比较
EXPLAIN ESTIMATE
SELECT * FROM tutorial.orders
WHERE order_date >= '2024-01-01' AND order_date < '2024-02-01';

-- -----------------------------------------------------
-- 6. 聚合查询优化
-- -----------------------------------------------------

-- 6.1 采样优化
--
-- ┌─────────────────────────────────────────────────────────────┐
-- │              采样优化                                             │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  SAMPLE: 快速估算                                             │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │                                                      │   │
-- │  │  SELECT user_id, count() / sample_factor            │   │
-- │  │  FROM orders SAMPLE 0.1                            │   │
-- │  │  GROUP BY user_id                                  │   │
-- │  │                                                      │   │
-- │  │  sample_factor: 系统自动提供采样系数                │   │
-- │  │                                                      │   │
-- │  │  ✓ 10% 采样 → 10x 速度提升                        │   │
-- │  │  ✓ 适用于估算/近似计算                             │   │
-- │  │                                                      │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

-- 使用采样
SELECT 
    count() / sample_factor AS estimated_total,
    uniqExact(user_id) / sample_factor AS estimated_users
FROM tutorial.orders
SAMPLE 0.1;

-- 6.2 近似聚合函数
--
-- ┌─────────────────────────────────────────────────────────────┐
-- │              近似聚合函数                                         │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  uniq: 精确去重 (慢)                                         │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  SELECT uniqExact(user_id) FROM orders;           │   │
-- │  │  时间: ~500ms (精确结果)                          │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                            │                                 │
-- │                            ▼                                 │
-- │  uniq: 近似去重 (快)                                         │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  SELECT uniq(user_id) FROM orders;                │   │
-- │  │  时间: ~50ms (近似结果,误差 < 3%)                │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  quantile: 近似分位数                                         │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  SELECT quantile(0.5)(total_amount) FROM orders;   │   │
-- │  │  SELECT quantileExact(0.5)(total_amount) FROM... │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

-- 精确 vs 近似
SELECT 'uniqExact' AS func, uniqExact(user_id) AS result FROM tutorial.orders
UNION ALL
SELECT 'uniq' AS func, uniq(user_id) AS result FROM tutorial.orders;

-- -----------------------------------------------------
-- 7. 物化视图优化
-- -----------------------------------------------------

-- 
-- ┌─────────────────────────────────────────────────────────────┐
-- │              物化视图优化                                         │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  物化视图: 预计算的聚合结果                                     │
-- │                                                              │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  原始表: orders (1000万行)                         │   │
-- │  │                                                      │   │
-- │  │  物化视图:                                          │   │
-- │  │  CREATE MATERIALIZED VIEW orders_daily             │   │
-- │  │  ENGINE = SummingMergeTree()                       │   │
-- │  │  ORDER BY (order_date, user_id) AS                │   │
-- │  │  SELECT                                             │   │
-- │  │      toDate(order_date) AS order_date,            │   │
-- │  │      user_id,                                       │   │
-- │  │      count() AS order_count,                      │   │
-- │  │      sum(total_amount) AS total_amount            │   │
-- │  │  FROM orders                                       │   │
-- │  │  GROUP BY toDate(order_date), user_id;            │   │
-- │  │                                                      │   │
-- │  │  结果: 约 10万行 (日活跃用户)                     │   │
-- │  │                                                      │   │
-- │  │  查询加速:                                          │   │
-- │  │  • 日活查询: 1ms (vs 500ms)                       │   │
-- │  │  • 月活查询: 10ms (vs 2s)                         │   │
-- │  │                                                      │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

-- 创建物化视图
DROP TABLE IF EXISTS tutorial.orders_daily_mv;
DROP TABLE IF EXISTS tutorial.orders_daily;

CREATE TABLE IF NOT EXISTS tutorial.orders_daily (
    order_date Date,
    user_id UInt32,
    order_count UInt64,
    total_amount Decimal(20, 2)
) ENGINE = SummingMergeTree()
ORDER BY (order_date, user_id);

CREATE MATERIALIZED VIEW IF NOT EXISTS tutorial.orders_daily_mv
TO tutorial.orders_daily
AS SELECT 
    toDate(order_date) AS order_date,
    user_id,
    count() AS order_count,
    sum(total_amount) AS total_amount
FROM tutorial.orders
GROUP BY toDate(order_date), user_id;

-- 等待物化视图填充
SYSTEM FLUSH LOGS;

-- 查询物化视图
SELECT * FROM tutorial.orders_daily
WHERE order_date = '2024-01-01'
LIMIT 10;

