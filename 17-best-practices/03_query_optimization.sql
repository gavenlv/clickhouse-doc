-- 1. 查询优化核心原则
-- -----------------------------------------------------

-- 
-- ┌─────────────────────────────────────────────────────────────┐
-- │              查询优化八大法则                                   │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  法则 1: 减少读取数据量                                        │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  ✓ 只选需要的列                                     │   │
-- │  │  ✓ 使用 WHERE 过滤                                │   │
-- │  │  ✓ 使用 LIMIT                                     │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  法则 2: 利用分区裁剪                                          │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  ✓ 查询条件包含分区键                              │   │
-- │  │  ✓ 避免在分区键上使用函数                          │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  法则 3: 使用物化视图                                          │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  ✓ 预聚合常用指标                                  │   │
-- │  │  ✓ 空间换时间                                      │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  法则 4: 优化聚合查询                                          │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  ✓ 使用 SAMPLE 采样                                │   │
-- │  │  ✓ 合理使用 GROUP BY                              │   │
-- │  │  ✓ 避免大结果集                                    │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  法则 5: 避免函数索引                                          │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  ✗ WHERE toDate(time) = '2024-01-01'             │   │
-- │  │  ✓ WHERE time >= '2024-01-01' AND time < '2024-01-02'│   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  法则 6: 使用 PREWHERE                                         │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  ✓ 自动优化: 只读取需要的列先过滤                   │   │
-- │  │                                                      │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  法则 7: 向量化执行                                            │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  ✓ 启用 vectorize_fusion = 1                      │   │
-- │  │  ✓ 避免复杂嵌套子查询                              │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  法则 8: 分布式查询优化                                        │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  ✓ 利用分片键过滤                                  │   │
-- │  │  ✓ 减少跨分片 JOIN                                │   │
-- │  │  ✓ 使用 GLOBAL 关键字                             │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

