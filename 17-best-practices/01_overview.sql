-- 4.1 内存配置
--
-- ┌─────────────────────────────────────────────────────────────┐
-- │              内存配置最佳实践                                   │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  max_memory_usage:                                          │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  推荐: 设置为服务器内存的 50-70%                     │   │
-- │  │                                                      │   │
-- │  │  示例: 64GB 服务器 → max_memory_usage = 32GB        │   │
-- │  │                                                      │   │
-- │  │  SET max_memory_usage = 32000000000;               │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  max_bytes_before_external_group_by:                        │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  超过阈值则使用磁盘排序                             │   │
-- │  │                                                      │   │
-- │  │  SET max_bytes_before_external_group_by = 2000000000;│ │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

-- 查看当前内存配置
SELECT 
    name,
    value,
    description
FROM system.settings
WHERE name LIKE '%memory%' OR name LIKE '%bytes%'
LIMIT 10;

-- 4.2 并发配置
--
-- ┌─────────────────────────────────────────────────────────────┐
-- │              并发配置最佳实践                                   │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  max_threads:                                                │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  推荐: CPU 核心数的 1-2 倍                         │   │
-- │  │                                                      │   │
-- │  │  过多线程会导致上下文切换开销                      │   │
-- │  │  合理设置: 4-16 线程                               │   │
-- │  │                                                      │   │
-- │  │  SET max_threads = 8;                             │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  max_concurrent_queries:                                     │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  控制同时运行的查询数量                             │   │
-- │  │                                                      │   │
-- │  │  防止资源耗尽                                      │   │
-- │  │                                                      │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

-- 查看当前线程配置
SELECT name, value FROM system.settings
WHERE name IN ('max_threads', 'max_concurrent_queries');

-- -----------------------------------------------------
-- 5. 监控和诊断
-- -----------------------------------------------------

-- 5.1 查询性能监控
--
-- ┌─────────────────────────────────────────────────────────────┐
-- │              性能监控关键指标                                    │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  关键指标:                                                   │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  • read_rows: 读取的行数                            │   │
-- │  │  • read_bytes: 读取的字节数                        │   │
-- │  │  • query_duration_ms: 查询耗时                     │   │
-- │  │  • memory_usage: 内存使用                          │   │
-- │  │  • CPU time: CPU 时间                              │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

-- 查看最近的查询性能
SELECT 
    query,
    read_rows,
    formatReadableSize(read_bytes) AS read_bytes,
    query_duration_ms,
    formatReadableSize(memory_usage) AS memory
FROM system.query_log
WHERE type = 'QueryFinish'
ORDER BY event_time DESC
LIMIT 5;

-- 5.2 慢查询分析
--
-- ┌─────────────────────────────────────────────────────────────┐
-- │              慢查询识别                                          │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  阈值定义:                                                    │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  • 慢查询: query_duration_ms > 1000ms              │   │
-- │  │  • 很慢查询: query_duration_ms > 10000ms          │   │
-- │  │  • 极慢查询: query_duration_ms > 60000ms           │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

-- 找出最慢的查询
SELECT 
    query,
    query_duration_ms,
    formatReadableSize(memory_usage) AS memory,
    read_rows
FROM system.query_log
WHERE type = 'QueryFinish'
  AND query_duration_ms > 1000
ORDER BY query_duration_ms DESC
LIMIT 10;

