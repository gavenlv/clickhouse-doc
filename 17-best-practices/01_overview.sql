-- 3. 查询性能对比
-- -----------------------------------------------------

-- 创建测试数据
DROP TABLE IF EXISTS tutorial.query_test;

CREATE TABLE IF NOT EXISTS tutorial.query_test (
    id UInt64,
    user_id UInt32,
    event_type String,
    event_date Date,
    value Float64,
    description String
) ENGINE = MergeTree()
PARTITION BY toYYYYMM(event_date)
ORDER BY (event_date, user_id);

INSERT INTO tutorial.query_test
SELECT 
    number,
    number % 10000,
    ['click', 'view', 'purchase', 'login'][number % 4 + 1],
    toDate('2024-01-01') + (number % 365),
    rand() / 100.0,
    repeat('x', 100)  -- 模拟大字段
FROM numbers(1000000);

-- 3.1 列选择对比
--
-- ┌─────────────────────────────────────────────────────────────┐
-- │              列选择性能对比                                    │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  Bad Practice: SELECT *                                     │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  SELECT * FROM query_test                          │   │
-- │  │  WHERE event_date = '2024-01-01';                  │   │
-- │  │                                                      │   │
-- │  │  读取: id, user_id, event_type, event_date,       │   │
-- │  │        value, description (6 列全部读取)           │   │
-- │  │                                                      │   │
-- │  │  时间: ~500ms, 内存: ~1GB                          │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  Good Practice: SELECT 具体列                                │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  SELECT user_id, count() FROM query_test           │   │
-- │  │  WHERE event_date = '2024-01-01'                  │   │
-- │  │  GROUP BY user_id;                                │   │
-- │  │                                                      │   │
-- │  │  读取: user_id, event_date (只读需要的列)         │   │
-- │  │                                                      │   │
-- │  │  时间: ~50ms, 内存: ~100MB                         │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

-- Bad: SELECT *
EXPLAIN PLAN
SELECT * FROM tutorial.query_test
WHERE event_date = '2024-01-01'
LIMIT 1;

-- Good: 只选需要的列
EXPLAIN PLAN
SELECT user_id, count() AS cnt 
FROM tutorial.query_test
WHERE event_date = '2024-01-01'
GROUP BY user_id;

-- 3.2 分区裁剪对比
--
-- ┌─────────────────────────────────────────────────────────────┐
-- │              分区裁剪效果对比                                   │
-- ├─────────────────────────────────────────────────────────────┤
-- │                                                              │
-- │  查询Without分区条件:                                        │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  SELECT count() FROM query_test;                   │   │
-- │  │                                                      │   │
-- │  │  扫描: 所有分区 (12 个月 × 多个 Parts)            │   │
-- │  │  时间: ~2s                                          │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- │  查询With分区条件:                                            │
-- │  ┌─────────────────────────────────────────────────────┐   │
-- │  │  SELECT count() FROM query_test                    │   │
-- │  │  WHERE event_date = '2024-01-01';                 │   │
-- │  │                                                      │   │
-- │  │  扫描: 仅 202401 分区                               │   │
-- │  │  时间: ~100ms                                       │   │
-- │  └─────────────────────────────────────────────────────┘   │
-- │                                                              │
-- └─────────────────────────────────────────────────────────────┘

-- 无分区条件
EXPLAIN ESTIMATE
SELECT count() FROM tutorial.query_test;

-- 有分区条件
EXPLAIN ESTIMATE
SELECT count() FROM tutorial.query_test
WHERE event_date = '2024-01-01';

